  /** Fabric estimate — returns { meters, formulaTh } */
  function estimateFabric(input) {
    var type = input.workType || 'bag';
    var bolt = parseFloat(input.fabricWidth) || 110;
    var seam = parseFloat(input.seamAllowance);
    if (isNaN(seam)) seam = 1.5;
    var L = parseFloat(input.lengthCm) || 0;
    var W = parseFloat(input.widthCm) || 0;
    var meters = 0;
    var formula = '';

    function panelMeters(len, wid, copies) {
      var needL = len + seam * 2;
      var needW = wid + seam * 2;
      var perRow = Math.max(1, Math.floor(bolt / needW));
      var rows = Math.ceil(copies / perRow);
      return (rows * needL) / 100;
    }

    if (type === 'bag') {
      if (L <= 0) L = 40;
      if (W <= 0) W = 35;
      meters = panelMeters(L, W, 2) + 0.15;
      formula =
        'กระเป๋า: ตัดผ้า ' +
        L +
        '×' +
        W +
        ' ซม. จำนวน 2 ชิ้น (เผื่อตะเข็บด้านละ ' +
        seam +
        ' ซม.) วางบนผ้ากว้าง ' +
        bolt +
        ' ซม. + เผื่อสายประมาณ 0.15 ม. = ประมาณ ' +
        meters.toFixed(2) +
        ' เมตร';
    } else if (type === 'pillow') {
      if (L <= 0) L = 50;
      if (W <= 0) W = 70;
      meters = panelMeters(L, W, 2) + 0.05;
      formula =
        'ปลอกหมอน: แผ่นผ้าประมาณ ' +
        L +
        '×' +
        W +
        ' ซม. × 2 ชิ้น เผื่อตะเข็บ ' +
        seam +
        ' ซม. บนผ้ากว้าง ' +
        bolt +
        ' ซม. ≈ ' +
        meters.toFixed(2) +
        ' เมตร';
    } else if (type === 'skirt') {
      if (L <= 0) L = 60;
      if (W <= 0) W = 150;
      var skirtLen = L + seam * 2 + 4;
      meters = Math.max(skirtLen / 100, (W + seam * 2) / bolt) * (W > bolt ? Math.ceil((W + seam * 2) / bolt) * (skirtLen / 100) : skirtLen / 100);
      if (W <= bolt) {
        meters = skirtLen / 100;
      } else {
        meters = Math.ceil((W + seam * 2) / bolt) * (skirtLen / 100);
      }
      meters = meters + 0.1;
      formula =
        'กระโปรง: ความยาวกระโปรง ' +
        L +
        ' ซม. + เผื่อเอว/ชาย/ตะเข็บ ≈ ใช้ตามความยาวบนผ้ากว้าง ' +
        bolt +
        ' ซม. (ถ้ารอบกว้างเกินความกว้างผ้า จะพับหลายแถว) ≈ ' +
        meters.toFixed(2) +
        ' เมตร';
    } else if (type === 'pants') {
      if (L <= 0) L = 100;
      if (W <= 0) W = 55;
      meters = panelMeters(L, W, 4) + 0.1;
      formula =
        'กางเกง: ชิ้นขาประมาณ ' +
        L +
        '×' +
        W +
        ' ซม. × 4 ชิ้น (หรือ 2 พับ) เผื่อตะเข็บ ' +
        seam +
        ' ซม. บนผ้ากว้าง ' +
        bolt +
        ' ซม. ≈ ' +
        meters.toFixed(2) +
        ' เมตร';
    } else if (type === 'top') {
      if (L <= 0) L = 65;
      if (W <= 0) W = 55;
      var body = panelMeters(L, W, 2);
      var sleeve = panelMeters(Math.max(20, L * 0.35), Math.max(30, W * 0.7), 2);
      meters = body + sleeve + 0.1;
      formula =
        'เสื้อแขนสั้น: ตัวเสื้อประมาณ ' +
        L +
        '×' +
        W +
        ' ซม. × 2 + แขน 2 ชิ้น เผื่อตะเข็บ ' +
        seam +
        ' ซม. บนผ้ากว้าง ' +
        bolt +
        ' ซม. ≈ ' +
        meters.toFixed(2) +
        ' เมตร';
    } else {
      meters = 1;
      formula = 'ประมาณคร่าว ๆ 1 เมตร — เลือกประเภทงานเพื่อคำนวณละเอียดขึ้น';
    }

    meters = Math.ceil(meters * 100) / 100;
    if (meters < 0.2) meters = 0.2;
    return { meters: meters, formulaTh: formula };
  }

